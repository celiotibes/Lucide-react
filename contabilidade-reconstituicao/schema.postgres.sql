CREATE TABLE IF NOT EXISTS contas_bancarias (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    banco           text NOT NULL,
    agencia         text,
    numero          text NOT NULL,
    titular         text NOT NULL,
    tipo            text NOT NULL CHECK (tipo IN ('corrente', 'poupanca', 'investimento')),
    ativa_desde     date,
    observacoes     text,
    -- Ver nota 7 acima: agencia é anulável e UNIQUE trata NULL como distinto
    -- em ambos os bancos — comportamento preservado, não é regressão.
    UNIQUE (banco, agencia, numero)
);

CREATE TABLE IF NOT EXISTS imoveis (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apelido         text NOT NULL,
    tipo            text NOT NULL CHECK (tipo IN ('apartamento', 'kitnet', 'sala_comercial', 'vaga_garagem', 'outro')),
    cidade          text,
    endereco        text,
    fracao_ideal    numeric(9,6) CHECK (fracao_ideal IS NULL OR fracao_ideal > 0), -- era REAL; fração 0-1, precisa de casas decimais finas
    area_m2         numeric(10,2),                                                -- era REAL
    financiado      boolean NOT NULL DEFAULT false,                                -- era INTEGER 0/1
    uso_pessoal     boolean NOT NULL DEFAULT false,                                -- era INTEGER 0/1

    matricula               text,
    matricula_mae           text,
    valor_aquisicao         numeric(14,2),           -- era REAL (dinheiro)
    valor_venal_atual       numeric(14,2),           -- era REAL (dinheiro)
    data_avaliacao_venal    date,
    regime_patrimonial      text NOT NULL DEFAULT 'proprio' CHECK (regime_patrimonial IN ('proprio', 'gestao_terceiros')),
    proprietario_nome       text,
    co_titular_nome         text
);

CREATE TABLE IF NOT EXISTS imovel_inventario_bens (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    imovel_id           integer NOT NULL REFERENCES imoveis(id),
    descricao           text NOT NULL,
    valor_reposicao     numeric(14,2),           -- era REAL (dinheiro)
    data_vistoria       date
);

CREATE TABLE IF NOT EXISTS financiamentos (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    imovel_id       integer NOT NULL REFERENCES imoveis(id),
    instituicao     text NOT NULL,
    sistema         text NOT NULL CHECK (sistema IN ('SAC', 'PRICE', 'OUTRO')),
    valor_contratado numeric(14,2) NOT NULL,             -- era REAL (dinheiro)
    taxa_juros_mensal numeric(9,4) NOT NULL DEFAULT 0.8,  -- era REAL (percentual a.m.)
    data_contrato   date NOT NULL,
    parcelas_total  integer NOT NULL,

    saldo_devedor_manual        numeric(14,2),   -- era REAL (dinheiro)
    parcela_mensal_manual       numeric(14,2),   -- era REAL (dinheiro)
    data_referencia_saldo_manual date,

    observacoes     text
);

CREATE TABLE IF NOT EXISTS dividas_consumo (
    id                      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo                    text NOT NULL CHECK (tipo IN ('consignado', 'emprestimo_pessoal', 'cartao_parcelado', 'outro')),
    instituicao             text NOT NULL,
    valor_contratado        numeric(14,2),          -- era REAL (dinheiro)
    saldo_devedor_atual     numeric(14,2) NOT NULL, -- era REAL (dinheiro)
    parcela_mensal          numeric(14,2) NOT NULL, -- era REAL (dinheiro)
    data_referencia_saldo   date NOT NULL,
    observacoes             text
);

CREATE TABLE IF NOT EXISTS obras (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    imovel_id       integer NOT NULL REFERENCES imoveis(id),
    descricao       text NOT NULL,
    data_inicio     date,
    data_fim        date,
    natureza        text NOT NULL CHECK (natureza IN ('capex', 'manutencao')),
    valor_total     numeric(14,2)   -- era REAL (dinheiro)
);

CREATE TABLE IF NOT EXISTS prestadores (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            text NOT NULL,
    cpf_cnpj        text,
    servico         text NOT NULL
);


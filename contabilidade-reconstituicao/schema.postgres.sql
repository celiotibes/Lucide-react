CREATE TABLE IF NOT EXISTS plano_de_contas (
    codigo          text PRIMARY KEY,
    descricao       text NOT NULL,
    grupo           text NOT NULL CHECK (grupo IN ('receita', 'despesa', 'pessoal', 'transferencia')),
    natureza        text NOT NULL CHECK (natureza IN ('debito', 'credito'))
);

CREATE TABLE IF NOT EXISTS transacoes (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conta_id            integer NOT NULL REFERENCES contas_bancarias(id),
    -- RISCO DATE — o mais alto do schema: normalizarData() em
    -- src/domain/parsers/csv.ts devolve a string CRUA quando ela não bate com
    -- YYYY-MM-DD nem DD/MM/YYYY (comentário 3 no topo do arquivo). Um .sqlite
    -- real pode já ter linha com `data` fora do formato ISO vinda de um CSV de
    -- banco com layout de data atípico. scripts/migrar-sqlite-para-postgres.mjs
    -- varre e reporta cada valor de `data`/`data_documento` que não bate com
    -- `\d{4}-\d{2}-\d{2}` ANTES de gerar o INSERT.
    data                date NOT NULL,
    data_competencia    date,                     -- opcional; mês do fato gerador (ver schema.sql)
    valor               numeric(14,2) NOT NULL,   -- era REAL (dinheiro)
    descricao_original  text NOT NULL,
    fitid               text,
    documento_fonte      text,
    plano_conta_codigo  text REFERENCES plano_de_contas(codigo),
    imovel_id           integer REFERENCES imoveis(id),
    contrato_id         integer REFERENCES contratos_locacao(id),
    prestador_id        integer REFERENCES prestadores(id),
    categorizado_por    text CHECK (categorizado_por IN ('regra', 'ia', 'manual')),
    revisado            boolean NOT NULL DEFAULT false,  -- era INTEGER 0/1
    UNIQUE (conta_id, fitid)
);


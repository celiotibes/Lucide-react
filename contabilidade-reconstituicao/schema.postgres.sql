CREATE TABLE IF NOT EXISTS contratos_locacao (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    imovel_id       integer NOT NULL REFERENCES imoveis(id),
    locatario       text NOT NULL,
    tipo            text NOT NULL CHECK (tipo IN ('residencial_fixo', 'airbnb_temporada')),
    valor_referencia numeric(14,2) NOT NULL,     -- era REAL (dinheiro)
    dia_vencimento  integer,
    -- RISCO DATE: data_inicio/data_fim vêm de formulário de cadastro (input
    -- type=date do navegador, formato ISO garantido pelo próprio input) — risco
    -- baixo, mas confira no .sqlite real antes da carga (ver item 3 acima).
    data_inicio     date NOT NULL,
    data_fim        date,
    indice_reajuste text CHECK (indice_reajuste IN ('igpm', 'ipca', 'nenhum')) DEFAULT 'igpm',

    percentual_aluguel_efetivo numeric(9,4) NOT NULL DEFAULT 100 CHECK (percentual_aluguel_efetivo BETWEEN 0 AND 100), -- era REAL

    multa_percentual numeric(9,4) NOT NULL DEFAULT 2.0,             -- era REAL
    multa_ate_dias integer NOT NULL DEFAULT 5,
    multa_percentual_substitutiva numeric(9,4) NOT NULL DEFAULT 10.0, -- era REAL
    juros_mensal_percentual numeric(9,4) NOT NULL DEFAULT 1.0,      -- era REAL
    indice_correcao_mora text CHECK (indice_correcao_mora IN ('igpm', 'ipca', 'nenhum')) DEFAULT 'ipca',
    honorarios_percentual numeric(9,4) NOT NULL DEFAULT 0,          -- era REAL
    dias_gatilho_judicial integer NOT NULL DEFAULT 9999,

    percentual_reajuste_primeira_renovacao numeric(9,4),            -- era REAL
    duracao_minima_meses integer NOT NULL DEFAULT 12,

    multa_rescisoria_teto_meses numeric(9,4) NOT NULL DEFAULT 3,    -- era REAL

    observacoes     text
);

CREATE TABLE IF NOT EXISTS contrato_reajustes (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contrato_id         integer NOT NULL REFERENCES contratos_locacao(id),
    data_vigencia       date NOT NULL,
    valor_anterior      numeric(14,2) NOT NULL,   -- era REAL (dinheiro)
    valor_novo          numeric(14,2) NOT NULL,   -- era REAL (dinheiro)
    percentual_aplicado numeric(9,4) NOT NULL,    -- era REAL
    criterio            text NOT NULL CHECK (criterio IN ('fixo', 'igpm', 'ipca')),
    eh_reajuste_anual   boolean NOT NULL DEFAULT true,  -- era INTEGER 0/1
    observacoes         text
);

CREATE TABLE IF NOT EXISTS contrato_locatarios (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contrato_id     integer NOT NULL REFERENCES contratos_locacao(id),
    nome            text NOT NULL,
    cpf             text,
    papel           text NOT NULL CHECK (papel IN ('locatario', 'responsavel_solidario')),
    telefone        text,
    email           text
);

CREATE TABLE IF NOT EXISTS caucoes (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contrato_id         integer NOT NULL REFERENCES contratos_locacao(id),
    valor_inicial       numeric(14,2) NOT NULL,  -- era REAL (dinheiro)
    data_deposito       date NOT NULL,
    indice_correcao     text NOT NULL CHECK (indice_correcao IN ('poupanca', 'igpm', 'ipca', 'nenhum')),
    data_devolucao      date,
    valor_devolvido     numeric(14,2),           -- era REAL (dinheiro)
    deducoes_descricao  text,
    deducoes_valor      numeric(14,2) DEFAULT 0, -- era REAL (dinheiro)
    observacoes         text
);

CREATE TABLE IF NOT EXISTS contrato_custeio_rubricas (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contrato_id     integer NOT NULL REFERENCES contratos_locacao(id),
    referencia      text,
    descricao       text NOT NULL,
    percentual      numeric(9,4),   -- era REAL
    valor_base      numeric(14,2)   -- era REAL (dinheiro)
);

CREATE TABLE IF NOT EXISTS contrato_franquia_hidrica (
    id                      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contrato_id             integer NOT NULL REFERENCES contratos_locacao(id),
    ocupacao_pessoas        integer NOT NULL,
    franquia_total_m3       numeric(10,3),   -- era REAL
    custo_estimado_reais    numeric(14,2)    -- era REAL (dinheiro)
);

CREATE TABLE IF NOT EXISTS indices_economicos (
    indice          text NOT NULL CHECK (indice IN ('poupanca', 'igpm', 'ipca')),
    -- RISCO DATE: mes_referencia é digitado como "primeiro dia do mês" —
    -- confira que todo valor gravado é um dia 01 válido (ex: 2023-01-01), sem
    -- variação de formato, antes da carga.
    mes_referencia  date NOT NULL,
    taxa_mensal     numeric(9,4) NOT NULL,   -- era REAL (percentual do mês)
    PRIMARY KEY (indice, mes_referencia)
);

CREATE TABLE IF NOT EXISTS declaracoes_fiscais (
    id                              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

-- ============================================================================
-- Schema de reconstituição contábil de locação de imóveis — versão PostgreSQL
-- (Supabase), tradução de schema.sql (SQLite/sql.js).
--
-- NÃO É A FONTE DA VERDADE ENQUANTO O APP RODAR EM SQLITE. schema.sql continua
-- sendo o schema de produção; este arquivo é o alvo da migração para Postgres,
-- gerado e mantido em paralelo. Ver PLANO-POSTGRES.md para a virada.
--
-- Validado sintaticamente com `psql` (PostgreSQL 16.13) contra um cluster local
-- efêmero (createdb + este arquivo com \i) — ver seção "Verificação" no relatório
-- de entrega. Não validado contra um projeto Supabase real (extensões
-- `pgcrypto`/`pgjwt`, `auth.users` etc. — ver rls.postgres.sql).
--
-- ============================================================================
-- REGRAS DE CONVERSÃO APLICADAS (armadilhas do enunciado, uma por uma)
-- ============================================================================
--
-- 1) "INTEGER PRIMARY KEY" no SQLite é alias do rowid e autoincrementa sozinho.
--    Em Postgres isso não existe — precisa de identidade explícita. Usamos
--    `GENERATED BY DEFAULT AS IDENTITY` (padrão SQL, sucessor de SERIAL) e não
--    `GENERATED ALWAYS AS IDENTITY`: o script de carga (scripts/migrar-sqlite-
--    para-postgres.mjs) precisa inserir os ids ORIGINAIS do SQLite para
--    preservar toda referência de FK já gravada — com ALWAYS, cada INSERT
--    exigiria `OVERRIDING SYSTEM VALUE`; com BY DEFAULT, um INSERT que informa
--    o id é aceito normalmente e só quem omite a coluna recebe o próximo valor
--    da sequência. Depois da carga inicial, rode
--    `SELECT setval(pg_get_serial_sequence('<tabela>','id'), (SELECT MAX(id) FROM <tabela>))`
--    para cada tabela — sem isso, o primeiro INSERT novo colide com um id já
--    importado. O script de migração já emite esses `setval` ao final.
--
-- 2) "DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP" → `timestamptz NOT NULL
--    DEFAULT now()`. Datetime "nu" (sem DEFAULT, ex: data_fechamento,
--    concluido_em) → `timestamptz` sem default. Usamos timestamptz (não
--    "timestamp without time zone"): os valores gravados por
--    `datetime('now')` no SQLite são UTC "sem fuso" — timestamptz normaliza
--    para UTC internamente e devolve já ajustado ao fuso da sessão, o que é o
--    comportamento certo para um sistema com usuários em fusos diferentes
--    (perito/advogado/contador não precisam estar no mesmo fuso do titular).
--    Se a aplicação hoje compara strings ISO literalmente (`datetime(?, '-30
--    days')` — ver item 2 do relatório), o tipo timestamptz é compatível com
--    comparação por `now() - interval`.
--
-- 3) "DATE" no SQLite é TEXT sem validação — aceita '', '31/12/2024',
--    '2024-13-40' sem reclamar. Em Postgres, `date` é um tipo real e REJEITA
--    tudo isso (confirmado empiricamente neste ambiente: `INSERT INTO d VALUES
--    ('')` e `('31/12/2024')` retornam "invalid input syntax for type date").
--    Isso é uma melhoria (passa a existir uma garantia que hoje não existe),
--    mas pode quebrar a CARGA de dado já salvo. Colunas DATE deste schema
--    populadas por texto digitado por humano (baixo risco) foram deixadas
--    `date` sem ressalva. As de risco REAL, com uma rota de entrada que já
--    tem hoje um fallback capaz de gravar string fora do formato ISO, estão
--    marcadas abaixo com "-- RISCO DATE:" e devem ser conferidas no arquivo
--    .sqlite real antes da carga (ver scripts/migrar-sqlite-para-postgres.mjs,
--    que valida e reporta cada valor de DATE que não bate com `\d{4}-\d{2}-\d{2}`
--    antes de gerar o INSERT em vez de deixar o Postgres rejeitar no meio da
--    carga). O caso concreto já identificado no código: `normalizarData()` em
--    src/domain/parsers/csv.ts faz `return bruta` (a string crua, sem
--    conversão) quando o valor não bate nem com `YYYY-MM-DD` nem com
--    `DD/MM/YYYY` — ou seja, `transacoes.data` e (por extensão)
--    `importacao_linhas.data` já podem conter data malformada vinda de CSV de
--    banco com formato atípico, hoje aceita em silêncio pelo SQLite.
--
-- 4) "REAL" para dinheiro: SQLite não tem type REAL de 4 bytes como o `real`
--    do Postgres — REAL no SQLite é sempre double de 8 bytes (mesma largura de
--    `double precision`). Ou seja, um mapeamento ingênuo REAL→real PERDERIA
--    precisão adicional (32 em vez de 64 bits) ALÉM do problema de fundo, que
--    é usar ponto flutuante binário para dinheiro: 0.1 + 0.2 não fecha exato
--    em double nem em SQLite nem em Postgres, e somas de centavos ao longo de
--    milhares de lançamentos produzem centavo fantasma que não bate no
--    balancete. RECOMENDAÇÃO (aplicada abaixo): `numeric(14,2)` para toda
--    coluna que é valor monetário em R$; `numeric(9,4)` para percentual/taxa
--    (precisa de mais casas que 2 — ex: 0.62% a.m.); `numeric(9,6)` para
--    frações/áreas. numeric é aritmética decimal exata (mesma família do
--    DECIMAL do padrão SQL) — impossível gerar centavo fantasma por
--    representação binária.
--    IMPACTO NO CÓDIGO (não corrigido aqui, só documentado): o driver `pg`
--    devolve coluna `numeric` como STRING (não `number`), justamente para não
--    reintroduzir erro de ponto flutuante ao trafegar por JS — todo código que
--    hoje faz `transacao.valor + outro.valor` ou passa o valor lido direto pra
--    conta matemática (a MAIORIA dos módulos de cálculo, ex:
--    src/domain/contabilidade, src/domain/financiamento,
--    src/domain/erp/ledger.ts) precisa parsear (`Number(x)` — reintroduzindo o
--    mesmo float — ou, melhor, uma lib decimal tipo decimal.js/big.js) antes
--    de operar, e formatar de volta como string com 2 casas ao gravar. Isso é
--    uma mudança de código real e abrangente, não cosmética — sinalizada aqui,
--    não feita (regra deste trabalho é não tocar em src/**).
--
-- 5) `CHECK (x IN (...))` — sintaxe idêntica nos dois bancos. Conferido: os
--    valores usados nos CHECK deste schema não têm acento nem aspas duplas
--    (são todos identificadores técnicos: 'apartamento', 'igpm', 'aberto' etc)
--    — nenhum precisou de escape adicional. Os poucos textos com acento do
--    schema (comentários, `descricao`) são dados de coluna livre, não valor de
--    CHECK, e nenhum problema de encoding aparece contanto que o banco
--    Postgres seja criado com `ENCODING 'UTF8'` (padrão do Supabase).
--
-- 6) `INTEGER` usado como boolean (`CHECK (x IN (0,1))`) → `boolean` nativo,
--    com `DEFAULT true/false` no lugar de `DEFAULT 1/0` e sem o CHECK (o tipo
--    já garante o domínio). Onze colunas neste schema são desse padrão — lista
--    completa nos comentários "-- era INTEGER 0/1" ao lado de cada uma.
--    IMPACTO NO CÓDIGO: `src/db/connection.ts::executar/consultar` tipam
--    parâmetros como `(string | number | null)[]` — não há `boolean` na união.
--    Todo INSERT/UPDATE que hoje manda `0`/`1` para essas 11 colunas (grep por
--    `financiado`, `uso_pessoal`, `revisado` etc — listado no item 2 do
--    relatório) precisaria mandar `true`/`false` (ou o driver `pg` aceitar
--    0/1 por coerção, o que NÃO faz para `boolean` — rejeita com erro de
--    tipo). Toda leitura que compara `row.revisado === 1` ou `=== 0` também
--    quebra, porque o valor volta como `true`/`false`, não `1`/`0`. E toda
--    consulta SQL que hoje escreve `WHERE revisado = 1` (não achei nenhuma no
--    código atual além dos módulos de teste, mas é o padrão SQLite) precisaria
--    virar `WHERE revisado` ou `WHERE revisado = true`.
--
-- 7) `UNIQUE` com NULL: TESTADO empiricamente neste ambiente (sql.js e
--    Postgres 16 reais, não de memória) — os dois bancos tratam NULL do MESMO
--    jeito por padrão: NULL nunca é igual a NULL num índice UNIQUE, então duas
--    linhas com a mesma combinação onde a coluna nullable é NULL nas duas NÃO
--    colidem, em NENHUM dos dois motores. Ou seja, ao contrário do que se
--    poderia supor, isto NÃO é uma diferença de comportamento entre SQLite e
--    Postgres — é um comportamento padrão SQL que os dois já compartilham. O
--    caso concreto do enunciado, `lotes_importacao UNIQUE
--    (arquivo_hash_sha256, conta_id)` com `conta_id` anulável, já tem esse
--    "furo" HOJE, em SQLite: reimportar o mesmo arquivo sem conta associada
--    (conta_id NULL) cria um segundo lote em vez de reabrir o existente — o
--    comentário original da tabela ("Reimportar o mesmo arquivo... reabre o
--    lote existente") só é verdade quando conta_id está preenchido. A migração
--    para Postgres NÃO piora nem resolve isso sozinha. O que a migração TORNA
--    POSSÍVEL, e que o SQLite não tem: `UNIQUE ... NULLS NOT DISTINCT`
--    (Postgres 15+), que trataria dois NULLs como iguais e fecharia o furo.
--    Deixamos comentado ao lado da constraint, como decisão explícita de
--    produto (mudaria comportamento observável — dois lotes sem conta viram
--    um só — o que pode ser desejado ou não).
--
-- ============================================================================
-- Achados ADICIONAIS de conversão (fora da lista do enunciado, encontrados na
-- leitura linha a linha):
--
-- a) Identificador `balancete_OK` (ledger_encerramentos) tem letra maiúscula.
--    Sem aspas, Postgres FOLDA todo identificador não citado para minúsculo:
--    a coluna nasce `balancete_ok`. `src/domain/fechamento/periodos.ts` lê
--    `encerramento?.balancete_OK` (case exato) — contra Postgres isso viria
--    `undefined` porque a linha devolvida pelo driver tem a chave
--    `balancete_ok`. Renomeada para `balancete_ok` (minúsculo) aqui, já que é
--    o nome real que o Postgres usaria de qualquer forma — CORRIGIR
--    src/domain/fechamento/periodos.ts (linhas 51 e 67) e o teste
--    periodos.test.ts:106 é trabalho de código, fora do escopo deste pacote,
--    mas está sinalizado no relatório e em PLANO-POSTGRES.md.
--
-- b) `imovel_gestao_ledger_integration.ts:746` faz `date(datetime('now'))` —
--    hoje um truque de cast duplo do SQLite; em Postgres a forma direta é
--    `CURRENT_DATE` ou `now()::date`. Sinalizado no item 2 do relatório.
--
-- ============================================================================


-- o texto antigo. Se for reescrito do zero para Postgres (sem migrar dado
-- histórico), aí sim vale `timestamptz` — decisão de produto, não técnica.
CREATE TABLE IF NOT EXISTS auditoria_log (
    id                      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "timestamp"             text,
    usuario_id              integer,
    usuario_nome            text,
    ip_origem               text,
    modulo_chamador         text,
    tipo_operacao           text,
    entidade_afetada        text,
    id_entidade             integer,
    descricao_alteracao     text,
    valor_anterior          text,
    valor_novo              text,
    hash_sha256             text,
    hash_anterior           text,
    status                  text,
    mensagem_erro           text,
    tempo_processamento_ms  integer,
    retencao_ate            text,
    assinado                boolean DEFAULT false,   -- era INTEGER 0/1 (DEFAULT 0, sem NOT NULL — preservado)
    assinatura_digital      text,
    criado_em               text
);

CREATE INDEX IF NOT EXISTS idx_auditoria_log_entidade ON auditoria_log(entidade_afetada, id_entidade);
CREATE INDEX IF NOT EXISTS idx_auditoria_log_timestamp ON auditoria_log("timestamp");


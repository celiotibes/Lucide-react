CREATE TABLE IF NOT EXISTS extrato_saldos_informados (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conta_id        integer NOT NULL REFERENCES contas_bancarias(id),
    data            date NOT NULL,
    saldo           numeric(14,2) NOT NULL,   -- era REAL (dinheiro)
    informado_em    timestamptz NOT NULL DEFAULT now(),
    informado_por   text,
    observacoes     text,
    UNIQUE (conta_id, data)
);

CREATE TABLE IF NOT EXISTS conciliacoes_bancarias (
    id                              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conta_id                        integer NOT NULL REFERENCES contas_bancarias(id),
    data_corte                      date NOT NULL,
    saldo_extrato                   numeric(14,2) NOT NULL,  -- era REAL (dinheiro)
    saldo_transacoes                numeric(14,2) NOT NULL,  -- era REAL (dinheiro)
    saldo_razao                     numeric(14,2) NOT NULL,  -- era REAL (dinheiro)
    diferenca_extrato_transacoes    numeric(14,2) NOT NULL,  -- era REAL (dinheiro)
    diferenca_transacoes_razao      numeric(14,2) NOT NULL,  -- era REAL (dinheiro)
    diferenca_extrato_razao         numeric(14,2) NOT NULL,  -- era REAL (dinheiro)
    fechada_sem_diferenca           boolean NOT NULL DEFAULT false,  -- era INTEGER 0/1
    realizada_em                    timestamptz NOT NULL DEFAULT now(),
    realizada_por                   text,
    observacoes                     text
);

CREATE INDEX IF NOT EXISTS idx_conciliacoes_bancarias_conta ON conciliacoes_bancarias(conta_id, data_corte);

CREATE TABLE IF NOT EXISTS conciliacoes_itens (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conciliacao_id      integer NOT NULL REFERENCES conciliacoes_bancarias(id),
    tipo                text NOT NULL CHECK (tipo IN (
        'nao_lancada_no_razao', 'triagem_pendente', 'classificacao_pendente',
        'lancamento_orfao_no_razao', 'residual_nao_identificado'
    )),
    descricao           text NOT NULL,
    quantidade          integer NOT NULL DEFAULT 0,
    valor               numeric(14,2) NOT NULL DEFAULT 0,   -- era REAL (dinheiro)
    afeta_diferenca     boolean NOT NULL DEFAULT true,      -- era INTEGER 0/1
    referencias_json     jsonb NOT NULL DEFAULT '[]'::jsonb  -- era TEXT NOT NULL DEFAULT '[]'; aqui pode virar jsonb de verdade (não é trilha de auditoria por hash, é lista de ids para a UI reconsultar)
);

CREATE INDEX IF NOT EXISTS idx_conciliacoes_itens_conciliacao ON conciliacoes_itens(conciliacao_id);

